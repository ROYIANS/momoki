import {spawn} from 'node:child_process';
import {randomUUID,randomBytes,createHash} from 'node:crypto';
import {mkdir,readFile,writeFile,open,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,relative} from 'node:path';
import {reserveStreamServer} from './sse-server.mjs';

const base=fileURLToPath(new URL('../',import.meta.url));
const root=resolve(base,'.acceptance',`run-${randomUUID()}`);
await mkdir(root,{recursive:true});
const token=randomBytes(32).toString('hex');
const server=await reserveStreamServer(root,token);
const env={...process.env,MOMOKI_STREAM_ENDPOINT:server.endpoint,MOMOKI_STREAM_TOKEN:token,MOMOKI_ACCEPTANCE_ROOT:root};
async function sources() {
    const result={};
    async function visit(path){for(const entry of await readdir(path,{withFileTypes:true})){if(entry.name.startsWith('.')||['node_modules','dist','gen','target','autogenerated'].includes(entry.name))continue;const file=resolve(path,entry.name);if(entry.isDirectory())await visit(file);else if(entry.isFile())result[relative(base,file)]=createHash('sha256').update(await readFile(file)).digest('hex');}}
    await visit(base);return result;
}
const before=await sources();
let app;
let outcome='incomplete';
const results=[];
const deadline=Date.now()+20*60*1000;
const pause=ms=>new Promise(accept=>setTimeout(accept,ms));
try {
    const log=await open(resolve(root,'build.log'),'wx');
    const built=await new Promise((accept,reject)=>{const child=spawn(process.execPath,[resolve(base,'scripts/build-app.mjs'),'--acceptance'],{cwd:base,env,stdio:['ignore',log.fd,log.fd]});child.once('error',reject);child.once('exit',(code,signal)=>accept({code,signal}));});
    await log.close();results.push({type:'build',...built});
    if(built.code!==0)throw new Error(`Packaged acceptance build failed; raw log ${root}/build.log`);
    const bundle=JSON.parse(await readFile(resolve(base,'.acceptance/acceptance-bundle.json'),'utf8'));
    const appLog=await open(resolve(root,'app.log'),'wx');
    const startedAt=Date.now();
    app=spawn(resolve(bundle.app,'Contents/MacOS/momoki'),[],{env,stdio:['ignore',appLog.fd,appLog.fd]});
    await appLog.close();
    await writeFile(resolve(base,'.acceptance/active-run.json'),JSON.stringify({version:1,root,app:bundle.app,pid:app.pid,startedAt,endpoint:server.endpoint,deadline},null,2)+'\n');
    console.log(`Actual acceptance app: ${bundle.app}\nRun evidence: ${root}\nPID ${app.pid}; controls supplied by UI owner. The finite runner awaits the persisted real packaged report.`);
    while(Date.now()<deadline){
        if(app.exitCode!==null)throw new Error(`Application exited ${app.exitCode} before complete acceptance`);
        try {
            const report=JSON.parse(await readFile(resolve(root,'report.json'),'utf8'));
            if(report.version!==1||!Array.isArray(report.events))throw new Error('Malformed actual packaged report');
            if(report.finishedAt){
                const failed=report.events.filter(event=>event.ok===false);
                if(failed.length)throw new Error(`Packaged assertions failed: ${failed.map(event=>event.name).join(', ')}`);
                if(report.events.length===0)throw new Error('Empty assertion report');
                outcome='passed';break;
            }
        }catch(error){if(error.code!=='ENOENT')throw error;}
        await pause(500);
    }
    if(outcome!=='passed')throw new Error('Finite packaged acceptance deadline expired without a complete assertion report');
} finally {
    // Kill only this runner's child. Root manual observations and measurements happen before completion.
    if(app&&app.exitCode===null)app.kill('SIGTERM');
    await server.close();
    const after=await sources();
    await writeFile(resolve(root,'runner-receipt.json'),JSON.stringify({version:1,outcome,before,after,stable:JSON.stringify(before)===JSON.stringify(after),results},null,2)+'\n');
}
